from __future__ import annotations

from decimal import Decimal
from io import BytesIO

from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas

from app.domain.models.workforce_payroll_adjustment import WorkforcePayrollAdjustment
from app.domain.models.workforce_payroll_entry import WorkforcePayrollEntry
from app.domain.models.workforce_payroll_period import WorkforcePayrollPeriod


def _fmt_money(value: Decimal | None, *, redact: bool) -> str:
    if redact:
        return "—"
    if value is None:
        return "—"
    return f"${value:,.2f}"


def _fmt_hours(value: Decimal | None, *, redact: bool) -> str:
    if redact:
        return "—"
    if value is None:
        return "—"
    return f"{value:.2f}"


def build_workforce_payslip_pdf_bytes(
    *,
    employee_name: str,
    redact: bool,
    entry: WorkforcePayrollEntry,
    period: WorkforcePayrollPeriod,
    adjustments: list[WorkforcePayrollAdjustment],
) -> bytes:
    buf = BytesIO()
    pdf = canvas.Canvas(buf, pagesize=letter)
    width, height = letter
    x = 72
    y = height - 72

    pdf.setFont("Helvetica-Bold", 16)
    pdf.drawString(x, y, "Payslip")
    y -= 28

    pdf.setFont("Helvetica", 10)
    pdf.drawString(x, y, f"Employee: {employee_name}")
    y -= 16
    pdf.drawString(x, y, f"Pay period: {period.start_date} → {period.end_date} · {period.status}")
    y -= 22

    pdf.setFont("Helvetica-Bold", 11)
    pdf.drawString(x, y, "Earnings")
    y -= 18
    pdf.setFont("Helvetica", 10)
    pdf.drawString(x, y, f"Salary type: {(entry.salary_type or '').strip() or '—'}")
    y -= 14
    st = (entry.salary_type or "").strip().upper()
    if st == "SALARIED":
        pdf.drawString(x, y, f"Base salary: {_fmt_money(entry.base_salary, redact=redact)}")
        y -= 14
        uld = entry.unpaid_leave_deduction or Decimal("0")
        pdf.drawString(x, y, f"Unpaid leave deduction: {_fmt_money(uld, redact=redact)}")
        y -= 14
    elif st == "HOURLY":
        pdf.drawString(x, y, f"Hourly rate: {_fmt_money(entry.hourly_rate, redact=redact)}")
        y -= 14
        om = entry.overtime_multiplier if not redact else None
        pdf.drawString(x, y, f"Overtime multiplier: {om if om is not None else '—'}")
        y -= 14
        pdf.drawString(
            x,
            y,
            f"Worked {entry.worked_minutes} min · Overtime {entry.overtime_minutes} min · Payable hours: {_fmt_hours(entry.payable_hours, redact=redact)}",
        )
        y -= 14

    pdf.setFont("Helvetica-Bold", 10)
    pdf.drawString(x, y, f"Gross pay: {_fmt_money(entry.gross_pay, redact=redact)}")
    y -= 22

    pdf.setFont("Helvetica-Bold", 11)
    pdf.drawString(x, y, "Adjustments")
    y -= 16
    pdf.setFont("Helvetica", 10)
    if not adjustments:
        pdf.drawString(x, y, "None")
        y -= 16
    else:
        for adj in adjustments:
            label = (adj.label or "").strip()
            kind = (adj.kind or "").strip()
            line = f"{kind}" + (f" — {label}" if label else "")
            pdf.drawString(x, y, line[:100])
            pdf.drawRightString(width - 72, y, _fmt_money(adj.amount, redact=redact))
            y -= 14

    y -= 8
    pdf.setFont("Helvetica-Bold", 11)
    pdf.drawString(x, y, f"Net pay: {_fmt_money(entry.net_pay, redact=redact)}")
    y -= 28
    pdf.setFont("Helvetica-Oblique", 8)
    pdf.drawString(x, y, "Generated by AI COO · Informational only · Verify totals against your records.")

    pdf.save()
    return buf.getvalue()
